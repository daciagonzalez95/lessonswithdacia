BEGIN;

CREATE TABLE IF NOT EXISTS public.parents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.gymnasts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id bigint NOT NULL REFERENCES public.parents(id),
  name text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.lesson_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  minutes integer NOT NULL UNIQUE,
  price_cents integer NOT NULL CHECK (price_cents >= 0),
  active integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS public.availability (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  weekday integer,
  specific_date text,
  start_time text NOT NULL,
  end_time text NOT NULL,
  CHECK ((weekday IS NULL) <> (specific_date IS NULL)),
  CHECK (weekday BETWEEN 0 AND 6 OR weekday IS NULL)
);

CREATE TABLE IF NOT EXISTS public.blocked_times (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_at text NOT NULL,
  end_at text NOT NULL,
  UNIQUE (start_at, end_at)
);

CREATE TABLE IF NOT EXISTS public.settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.policy_versions (
  id text PRIMARY KEY,
  content text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id text PRIMARY KEY,
  parent_id bigint NOT NULL REFERENCES public.parents(id),
  gymnast_id bigint NOT NULL REFERENCES public.gymnasts(id),
  lesson_type_id bigint NOT NULL REFERENCES public.lesson_types(id),
  start_at text NOT NULL,
  end_at text NOT NULL,
  status text NOT NULL,
  notes text,
  policy_version text NOT NULL REFERENCES public.policy_versions(id),
  policy_accepted_at text NOT NULL,
  manage_token_hash text NOT NULL,
  hold_expires_at text,
  stripe_session_id text UNIQUE,
  created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id text NOT NULL REFERENCES public.bookings(id),
  stripe_payment_id text UNIQUE,
  stripe_session_id text UNIQUE,
  amount_cents integer NOT NULL,
  status text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.webhook_events (
  id text PRIMARY KEY,
  received_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.reminders (
  booking_id text PRIMARY KEY REFERENCES public.bookings(id),
  sent_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS bookings_times ON public.bookings(start_at,end_at,status);
CREATE UNIQUE INDEX IF NOT EXISTS availability_unique ON public.availability
  (coalesce(weekday, -1), coalesce(specific_date, ''), start_time, end_time);

